// Visual acceptance for the redesigned workspace; uses demo data only.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const { execFileSync } = require('node:child_process')
const path = require('node:path')
const assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..')
let browser
;(async () => {
  browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://localhost:18080/login', { waitUntil: 'networkidle' })
  const captcha = JSON.parse(execFileSync('docker', ['compose', '-f', path.join(root, 'compose.delivery.yaml'), 'exec', '-T', 'redis', 'redis-cli', '--raw', 'get', 'validate:code'], { encoding: 'utf8', cwd: root }))
  await page.locator('input[autocomplete="current-password"]').fill('Zx@123456')
  await page.getByPlaceholder('输入右侧数字').fill(captcha)
  await page.getByRole('button', { name: /进入工作空间/ }).click()
  await page.waitForURL('**/home')
  await page.waitForLoadState('networkidle')
  await page.waitForTimeout(1200)
  await page.locator('.el-message').waitFor({ state: 'hidden' })
  assert.equal(await page.locator('.zx-stat-card').count(), 6)
  await page.screenshot({ path: path.join(__dirname, '知序UI-工作总览.png'), fullPage: true })
  await page.getByRole('button', { name: '展开或收起导航' }).click()
  assert(await page.locator('.zx-shell').evaluate(el => el.classList.contains('zx-nav-collapsed')))
  await page.getByRole('button', { name: '展开或收起导航' }).click()
  const routes = {
    '/system/staff': '员工档案', '/system/department': '部门与组织', '/system/docs': '知识文档',
    '/permission/role': '角色管理', '/permission/menu': '菜单权限',
    '/performance/attendance': '考勤记录', '/performance/leave': '假期配置', '/performance/overtime': '加班与调休',
    '/money/salary': '薪资明细', '/money/insurance': '五险一金', '/money/city': '参保城市'
  }
  for (const [route, title] of Object.entries(routes)) {
    await page.goto('http://localhost:18080' + route, { waitUntil: 'networkidle' })
    assert.equal(await page.locator('.zx-page-heading h1').innerText(), title)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), route + ' overflow')
    const table = page.locator('.common-table > .el-table').first()
    assert(await table.isVisible(), route + ' table is missing')
    const pager = page.locator('.common-table .pager').first()
    if (await pager.count()) assert(await pager.isVisible(), route + ' pagination is missing')
    console.log('PASS layout ' + route)
  }
  await page.goto('http://localhost:18080/system/staff', { waitUntil: 'networkidle' })
  await page.locator('.manage-header').getByPlaceholder('请输入姓名').fill('陈晨')
  await page.locator('.manage-header').getByRole('button', { name: /^搜索/ }).click()
  await page.waitForLoadState('networkidle')
  await page.locator('.el-table__fixed').first().getByText('陈晨 · 员工', { exact: true }).waitFor()
  await page.locator('.manage-header').getByRole('button', { name: /^重置/ }).click()
  await page.waitForLoadState('networkidle')
  await page.locator('.pager .btn-next').click()
  await page.waitForLoadState('networkidle')
  assert.equal(await page.locator('.pager .el-pager li.active').innerText(), '2')
  await page.locator('.pager .btn-prev').click()
  await page.waitForLoadState('networkidle')
  await page.screenshot({ path: path.join(__dirname, '知序UI-员工档案.png'), fullPage: true })
  await page.locator('.el-table__fixed-right').getByRole('button', { name: /^编辑/ }).first().click()
  const dialog = page.locator('.el-dialog__wrapper:visible').first()
  await dialog.waitFor()
  assert(await dialog.getByPlaceholder('请输入姓名').inputValue())
  await page.waitForTimeout(350)
  await page.screenshot({ path: path.join(__dirname, '知序UI-员工表单.png'), fullPage: true })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  console.log('PASS staff search, reset, pagination, edit dialog and cancellation')
  await page.goto('http://localhost:18080/chat', { waitUntil: 'networkidle' })
  assert(await page.locator('.chat-container').evaluate(el => el.querySelector('.chat-input-wrapper').getBoundingClientRect().bottom <= el.getBoundingClientRect().bottom + 1), 'chat composer must remain inside its panel')
  await page.screenshot({ path: path.join(__dirname, '知序UI-制度问答.png'), fullPage: true })
  await page.locator('.zx-prompt-grid button').first().click()
  assert.equal(await page.locator('.chat-input-card textarea').inputValue(), '报销需要哪些材料？')
  await page.locator('.chat-input-actions button').click()
  await page.locator('.assistant .chat-text').filter({ hasText: '发票' }).waitFor({ timeout: 30000 })
  await page.getByText('参考来源', { exact: true }).waitFor()
  console.log('PASS suggested question, complete SSE answer and citations')
  await page.getByRole('button', { name: '展开或收起导航' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  for (const route of ['/home', '/system/staff', '/chat']) {
    await page.goto('http://localhost:18080' + route, { waitUntil: 'networkidle' })
    await page.waitForTimeout(route === '/home' ? 1200 : 200)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), route + ' mobile overflow')
    if (route === '/system/staff') assert(await page.locator('.el-table__body-wrapper').first().getByText('知序管理员', { exact: true }).isVisible(), 'mobile fixed columns must not hide employee names')
    await page.screenshot({ path: path.join(__dirname, '知序UI-移动' + (route === '/home' ? '工作台' : route === '/chat' ? '问答' : '员工') + '.png'), fullPage: true })
  }
  assert(await page.locator('.chat-container').evaluate(el => el.querySelector('.chat-input-wrapper').getBoundingClientRect().bottom <= el.getBoundingClientRect().bottom + 1), 'mobile composer must remain inside its panel')
  await page.getByRole('button', { name: '展开或收起导航' }).click()
  assert(await page.locator('.zx-aside').isVisible())
  await page.locator('.zx-nav-backdrop').click({ position: { x: 350, y: 200 } })
  assert(!(await page.locator('.zx-aside').isVisible()))
  assert.equal(errors.length, 0, errors.join('\n'))
  await browser.close()
  console.log('PASS mobile workspace, tables, chat, drawer and zero page errors')
})().catch(async error => { console.error(error); if (browser) await browser.close(); process.exitCode = 1 })
